"""Write a copy of index.html for every route so GitHub Pages can serve clean URLs."""
import sys, os

DOCS = sys.argv[1]
PAGES = {
    'about': '비교파트 소개', 'apartments': '단지 목록 | 비교파트', 'apt': '비교파트', 'commute': '출퇴근 스트레스 | 비교파트',
    'compare': '비교하기 | 비교파트', 'rebuild': '재건축 가능성 | 비교파트', 'reviews': '리뷰 | 비교파트',
    'safety': '안심거래센터 | 비교파트', 'school': '최적의 학군 | 비교파트', 'tools': '분석 도구 | 비교파트',
    'value': '맞춤 추천 | 비교파트', '404': '페이지를 찾을 수 없어요 | 비교파트',
}
src = open(os.path.join(DOCS, 'index.html')).read()
for name, title in PAGES.items():
    s = src.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by tools/build_pages.py from index.html — edit index.html, not this file. -->', 1)
    s = s.replace('<title>비교파트</title>', '<title>%s</title>' % title, 1)
    if name == '404':
        s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="/">', 1)
    open(os.path.join(DOCS, name + '.html'), 'w').write(s)
print('wrote', len(PAGES), 'pages')
